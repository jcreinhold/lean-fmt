#!/usr/bin/env python3
"""Fail when prose quotes a corpus figure that the evidence no longer supports.

`RLF-FINAL`. This is the gate `results/01-commands.md` asked for and did not build:

    "Re-running the probe after touching `LeanFmt/` is part of the work, not a tidy-up; a gate
     that diffed the quoted figures against the evidence would be better and does not exist."

**Why the hazard is real rather than theoretical.** This repository *is* the printer's corpus, so
every figure describing it moves whenever `LeanFmt/` changes -- and the prompts that change
`LeanFmt/` are not the prompts that wrote the sentences quoting it. `RLF-EXTENSIONS` added
`Tree.mayCollapse` and left four files claiming a node count from two prompts earlier. Nothing
failed, because nothing was looking. `evidence/01-projection-shape.txt` is regenerated by
`run-projection-shape.sh` and is always right; the prose around it is what rots.

**What is gated and what is deliberately not.** Only files that claim to describe the corpus *now*:
`LeanFmt/Printer.lean`'s docstrings, `notes/01-command-printing.md`, and `state/current.md`. The
`results/NN-*.md` notes are **snapshots of what a prompt measured when it ran** and are excluded on
purpose -- rewriting their figures to today's would claim `RLF-COMMANDS` measured something it did
not. That is a difference in kind, not a gap: one is a live claim, the other is history.

**A pattern that stops matching is a failure, not a skip.** Each figure is found by a regex naming
the sentence that carries it. Reword the sentence and this fails with `pattern never matched`, which
forces the reworder to look at the number. A gate that silently matched nothing would be worse than
no gate -- that is the `misordered=0` mistake `state/current.md` records, and this file refuses to
repeat it.

usage: check-quoted-figures.py [--evidence PATH]
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
STACK = REPO / "docs/projects/ruff-03-language-formatting"
EVIDENCE = STACK / "evidence/01-projection-shape.txt"


def read_evidence(path: pathlib.Path) -> dict[str, int]:
    """Pull the figures the prose quotes out of the probe's own output."""
    text = path.read_text()

    def grab(pattern: str) -> int:
        m = re.search(pattern, text, re.M)
        if not m:
            sys.exit(f"FAIL {path} has no match for {pattern!r}; the probe's format changed.")
        return int(m.group(1).replace(",", ""))

    nodes = grab(r"^modules_analyzed=\d+ skipped=\d+ nodes=(\d+)$")
    empty = grab(r"^empty_nodes=(\d+) ")
    ambiguous = grab(r"^empty_nodes_with_ambiguous_placement=(\d+) ")
    commands = grab(r"^# command kinds in the corpus \((\d+) commands")
    declarations = grab(r"^(\d+)\tLean\.Parser\.Command\.declaration$")
    claimable = grab(r"^(\d+)\tstructurally claimed: shell laid out$")
    # The other three command kinds with a layout. Read from the probe rather than written as a
    # constant, so that `canonical` below is the printer's own identity re-derived from evidence
    # (`claimable + namespace + end + open`) instead of a magic number that happens to be right.
    namespaces = grab(r"^(\d+)\tLean\.Parser\.Command\.namespace$")
    ends = grab(r"^(\d+)\tLean\.Parser\.Command\.end$")
    opens = grab(r"^(\d+)\tLean\.Parser\.Command\.open$")
    # The addends of that identity are quoted too, and they drifted once while the sum was still
    # being checked: the prose read `779 + 25 + 25 + 7`, which is 836, not the 859 it claimed.
    # Nothing caught it because the three small numbers were baked into this file's regexes as
    # literals. They are read from the probe now, and checked where the prose spells them.
    kinds = grab(r"^# command kinds in the corpus \(\d+ commands, (\d+) distinct kinds\)$")
    sections = grab(r"^(\d+)\tLean\.Parser\.Command\.section$")
    return {
        "sections": sections,
        "nodes": nodes,
        "empty": empty,
        "ambiguous": ambiguous,
        "commands": commands,
        "kinds": kinds,
        "declarations": declarations,
        "claimable": claimable,
        "namespaces": namespaces,
        "ends": ends,
        "opens": opens,
        "canonical": claimable + namespaces + ends + opens,
    }


AGREEMENT = STACK / "evidence/01-coverage-agreement.txt"


def read_agreement(path: pathlib.Path, probe_canonical: int) -> dict[str, int]:
    """The printer's own coverage count, which the shape probe cannot derive.

    `canonical=` is what the printer laid out; the probe's formula is what the *structure* allows,
    and the two are not the same number (`evidence/01-coverage-agreement.txt`: the formula omits
    `section`, and the printer refuses one shell at a runtime guard). The prose quotes both, so both
    need a source. The consistency check below is the point: if the shape probe is regenerated and
    this file is not, the pair of evidence files disagrees and that is a failure, not a figure to
    average -- it is exactly the drift that let 859 == 859 read as agreement for two prompts.
    """
    text = path.read_text()
    m = re.search(r"^printer_total=(\d+) +probe_total=(\d+) ", text, re.M)
    if not m:
        sys.exit(f"FAIL {path} has no printer_total/probe_total line; the comparison's format changed.")
    printer_total, probe_total = int(m.group(1)), int(m.group(2))
    if probe_total != probe_canonical:
        sys.exit(
            f"FAIL {path} records probe_total={probe_total}, but the shape probe now implies "
            f"{probe_canonical}.\n    The two evidence files were regenerated apart. Re-run the "
            f"per-module comparison the file documents."
        )
    return {"printer_total": printer_total}


def commas(n: int) -> str:
    return f"{n:,}"


def pct(part: int, whole: int) -> str:
    return f"{100.0 * part / whole:.1f}"


def build_checks(f: dict[str, int]) -> list[tuple[str, str, str]]:
    """(file, regex with one capture group, expected capture).

    Every regex must match at least once, and every match must equal the expectation.
    """
    nodes, empty, ambig = f["nodes"], f["empty"], f["ambiguous"]
    printer = "LeanFmt/Printer.lean"
    notes = "docs/projects/ruff-03-language-formatting/notes/01-command-printing.md"
    state = "docs/projects/ruff-03-language-formatting/state/current.md"

    return [
        # --- Printer.lean's module docstring: the projection's shape ---
        (printer, r"repository \(([\d,]+) nodes, `evidence/01-projection-shape\.txt`\)", commas(nodes)),
        (printer, r"`evidence/01-projection-shape\.txt`\), ([\d,]+) nodes \(\d+\.\d+%\) carry no token", commas(empty)),
        (printer, r"([\d,]+) nodes \(\d+\.\d+%\) carry no token at\n", commas(empty)),
        (printer, r"nodes \((\d+\.\d+)%\) carry no token at", pct(empty, nodes)),
        (printer, r"For ([\d,]+) of them \(\d+\.\d+% of all nodes\)", commas(ambig)),
        (printer, r"For [\d,]+ of them \((\d+\.\d+)% of all nodes\)", pct(ambig, nodes)),
        (printer, r"correct for the (\d+\.\d+)% that carry", pct(nodes - empty, nodes)),
        (printer, r"unaffected by all ([\d,]+) ambiguous placements", commas(ambig)),
        (printer, r"the common one: (\d+\.\d+)% of nodes are empty", pct(empty, nodes)),
        (printer, r"measures (\d+\.\d+)% of nodes to be exactly that ambiguous", pct(ambig, nodes)),
        (printer, r"index order agrees with byte order \(0 violations over ([\d,]+) nodes\)", commas(nodes)),
        # --- notes/01: the design note's census ---
        (notes, r"\| nodes whose subtree contains no token at all \| \*\*([\d,]+) — \d+\.\d+%\*\* \|", commas(empty)),
        (notes, r"\| nodes whose subtree contains no token at all \| \*\*[\d,]+ — (\d+\.\d+)%\*\* \|", pct(empty, nodes)),
        (notes, r"whose parent also has direct token children \| \*\*([\d,]+) — \d+\.\d+% of all nodes\*\* \|", commas(ambig)),
        (notes, r"whose parent also has direct token children \| \*\*[\d,]+ — (\d+\.\d+)% of all nodes\*\* \|", pct(ambig, nodes)),
        (notes, r"For ([\d,]+) of [\d,]+ nodes, an empty", commas(ambig)),
        (notes, r"For [\d,]+ of ([\d,]+) nodes, an empty", commas(nodes)),
        (notes, r"unaffected by all ([\d,]+) ambiguous placements", commas(ambig)),
        (notes, r"\*\*(\d+) commands in \d+ distinct kinds\*\*", str(f["commands"])),
        (notes, r"\*\*\d+ commands in (\d+) distinct kinds\*\*", str(f["kinds"])),
        (notes, r"\| `Lean\.Parser\.Command\.declaration` \| (\d+) \|", str(f["declarations"])),
        (notes, r"2734 commands against this repository's (\d+)", str(f["commands"])),
        (notes, r"the census above shows 0 in (\d+) commands here and 181", str(f["commands"])),
        # --- state/current.md: the live state ---
        (state, r"\*\*(\d+) of the corpus's \d+ commands take a cited", str(f["printer_total"])),
        (state, r"\*\*\d+ of the corpus's (\d+) commands take a cited", str(f["commands"])),
        (state, r"`open` \(\d+\), (\d+) `section`", str(f["sections"])),
        (state, r"the shell of (\d+) of\n\d+ declarations", str(f["claimable"])),
        (state, r"the shell of \d+ of\n(\d+) declarations", str(f["declarations"])),
        (state, r"floors the corpus total: \*\*(\d+) of \d+\*\*", str(f["printer_total"])),
        (state, r"floors the corpus total: \*\*\d+ of (\d+)\*\*", str(f["commands"])),
        (state, r"finds (\d+) of \d+\n\s*declarations claimable", str(f["claimable"])),
        (state, r"finds \d+ of (\d+)\n\s*declarations claimable", str(f["declarations"])),
        (state, r"`namespace` \((\d+)\), `end` \(\d+\), `open` \(\d+\)", str(f["namespaces"])),
        (state, r"`namespace` \(\d+\), `end` \((\d+)\), `open` \(\d+\)", str(f["ends"])),
        (state, r"`namespace` \(\d+\), `end` \(\d+\), `open` \((\d+)\)", str(f["opens"])),
        (state, r"the printer, in Lean, lays out (\d+)", str(f["printer_total"])),
        (state, r"exactly (\d+) and the printer lays out both", str(f["sections"])),
        (state, r"counts (\d+) = \d+ \+ \d+ `namespace` \+ \d+ `end` \+ \d+ `open`", str(f["canonical"])),
        (state, r"counts \d+ = (\d+) \+ \d+ `namespace` \+ \d+ `end` \+ \d+ `open`", str(f["claimable"])),
        (state, r"counts \d+ = \d+ \+ (\d+) `namespace` \+ \d+ `end` \+ \d+ `open`", str(f["namespaces"])),
        (state, r"counts \d+ = \d+ \+ \d+ `namespace` \+ (\d+) `end` \+ \d+ `open`", str(f["ends"])),
        (state, r"counts \d+ = \d+ \+ \d+ `namespace` \+ \d+ `end` \+ (\d+) `open`", str(f["opens"])),
        (state, r"\*\*That (\d+) commands take the layout", str(f["printer_total"])),
    ]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--evidence", default=str(EVIDENCE))
    parser.add_argument("--agreement", default=str(AGREEMENT))
    args = parser.parse_args()

    figures = read_evidence(pathlib.Path(args.evidence))
    figures.update(read_agreement(pathlib.Path(args.agreement), figures["canonical"]))
    failures: list[str] = []
    checked = 0

    for relpath, pattern, expected in build_checks(figures):
        path = REPO / relpath
        text = path.read_text()
        matches = re.findall(pattern, text)
        if not matches:
            failures.append(
                f"{relpath}: pattern never matched: {pattern}\n"
                f"    The sentence carrying this figure was reworded or removed. Re-point the gate\n"
                f"    at it -- a check that matches nothing is worse than no check."
            )
            continue
        for got in matches:
            checked += 1
            if got != expected:
                failures.append(
                    f"{relpath}: quotes {got!r} where {args.evidence} says {expected!r}\n"
                    f"    pattern: {pattern}\n"
                    f"    Re-run experiments/run-projection-shape.sh and update the prose."
                )

    if failures:
        print("FAIL prose quotes a figure the evidence does not support.\n", file=sys.stderr)
        print(
            "This repository is the printer's own corpus, so these move whenever `LeanFmt/`\n"
            "changes. The evidence file is regenerated and authoritative; the prose is not.\n",
            file=sys.stderr,
        )
        for f in failures:
            print(f"  {f}\n", file=sys.stderr)
        return 1

    print(f"quoted figures agree with {args.evidence} ({checked} checked)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
